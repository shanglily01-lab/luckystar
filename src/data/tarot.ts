function minors(): TarotCard[] {
  const cards: TarotCard[] = [];
  for (const suit of SUITS) {
    for (const rank of RANKS) {
      cards.push({
        id: `${suit.name}-${rank.name}`,
        name: `${suit.name}${rank.name}`,
        arcana: suit.name,
        upright: `${suit.theme}这一面：${rank.up}`,
        reversed: `${suit.theme}走偏时：${rank.down}`,
      });
    }
  }
  return cards;
}

