export const HEXAGRAMS: Hexagram[] = RAW.map(([name, bits, summary, advice], index) => ({
  no: index + 1,
  name,
  lines: bits.split('').map((bit) => Number(bit)),
  summary,
  advice,
}));

const TRIGRAMS: { name: string; lines: number[] }[] = [
  { name: '乾', lines: [1, 1, 1] },
  { name: '兑', lines: [1, 1, 0] },
  { name: '离', lines: [1, 0, 1] },
  { name: '震', lines: [1, 0, 0] },
  { name: '巽', lines: [0, 1, 1] },
  { name: '坎', lines: [0, 1, 0] },
  { name: '艮', lines: [0, 0, 1] },
  { name: '坤', lines: [0, 0, 0] },
];

export function trigramByNumber(n: number) {
  const index = ((n % 8) + 8) % 8;
  return TRIGRAMS[index === 0 ? 7 : index - 1];
}

export function findHexagram(lines: number[]): Hexagram {
  const key = lines.join('');
  return HEXAGRAMS.find((item) => item.lines.join('') === key) ?? HEXAGRAMS[0];
}

export function hexSymbol(no: number) {
  return String.fromCodePoint(0x4dc0 + no - 1);
}

